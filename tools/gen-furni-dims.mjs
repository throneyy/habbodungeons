// Generates js/furniDims.js from the extracted props themselves.
//
// The old file claimed this header and no such generator existed: the table
// was hand-maintained in parallel with xdim/ydim that already lived in every
// public/assets/props/<id>/data.json, so a re-extraction could silently
// disagree with it. Now the module is derived, and `--check` fails if the
// committed file has drifted from the data.
//
//   node tools/gen-furni-dims.mjs           # rewrite js/furniDims.js
//   node tools/gen-furni-dims.mjs --check   # exit 1 if it would change
//
// Emits two tables:
//   FURNI_DIMS  — multi-tile footprints [xdim, ydim] (unchanged shape and
//                 contents; js/room.js reads it to auto-derive seat tiles)
//   FURNI_LOGIC — zdim + Habbo's own walkability flags, mirrored into the
//                 data.json files by tools/gen-furni-logic.mjs. Nothing reads
//                 this yet — wiring it into collision and depth sorting is a
//                 separate step.

import { readdir, readFile, writeFile } from 'node:fs/promises';

const PROPS = new URL('../public/assets/props/', import.meta.url);
const OUT = new URL('../js/furniDims.js', import.meta.url);

const check = process.argv.includes('--check');
const dirs = (await readdir(PROPS, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort();

const props = [];
for (const id of dirs) {
  const raw = await readFile(new URL(`${id}/data.json`, PROPS), 'utf8').catch(() => null);
  if (raw) props.push(JSON.parse(raw));
}

const dimLines = props
  .filter((p) => (p.xdim ?? 1) !== 1 || (p.ydim ?? 1) !== 1)
  .map((p) => `  ${p.id}: [${p.xdim}, ${p.ydim}],`);

// Only what differs from the defaults below: a solid 1-unit block nobody can
// stand, sit or lie on. Keeps the table a quarter of the size it would be if
// every prop spelled out five fields, and makes the exceptions readable.
const FLAGS = [['canstandon', 'stand'], ['cansiton', 'sit'], ['canlayon', 'lay'], ['canputstuffon', 'put']];
const logicLines = [];
let unknown = 0;
for (const p of props) {
  if (p.zdim == null) {
    unknown++;
    continue; // no furnidata, no override: the accessor's defaults apply
  }
  const fields = [];
  if (p.zdim !== 1) fields.push(`z: ${p.zdim}`);
  for (const [src, short] of FLAGS) if (p[src] === true) fields.push(`${short}: true`);
  if (!fields.length) continue;
  logicLines.push(`  ${p.id}: { ${fields.join(', ')} },`);
}

const text = `// GENERATED by tools/gen-furni-dims.mjs — do not edit by hand.
// Source of truth: public/assets/props/<id>/data.json (xdim/ydim from the SWF
// extraction, zdim + flags mirrored from furnidata by gen-furni-logic.mjs).
// Multi-tile furni footprint dims [xdim, ydim] at dir 0/4 (dirs 2/6 swap).
// Single-tile furni are omitted (default [1, 1]).
export const FURNI_DIMS = {
${dimLines.join('\n')}
};

// Habbo's own per-TYPE furni logic: zdim (physical stack height — what decides
// what stacks on what) and the walkability flags. Entries list only what
// differs from FURNI_DEFAULTS, and a prop absent here is a solid 1-unit block.
// NOT the per-layer z in a furni's visualization XML (that orders sprites
// within one item — js/props.js uses it for seat-front cutouts).
export const FURNI_DEFAULTS = { zdim: 1, canStandOn: false, canSitOn: false, canLayOn: false, canPutStuffOn: false };

export const FURNI_LOGIC = {
${logicLines.join('\n')}
};

// Resolved logic for a furni id, defaults filled in.
export function furniLogic(id) {
  const e = FURNI_LOGIC[id];
  if (!e) return { ...FURNI_DEFAULTS };
  return {
    zdim: e.z ?? FURNI_DEFAULTS.zdim,
    canStandOn: e.stand === true,
    canSitOn: e.sit === true,
    canLayOn: e.lay === true,
    canPutStuffOn: e.put === true,
  };
}
`;

const prev = await readFile(OUT, 'utf8').catch(() => '');
const changed = prev !== text;
if (changed && !check) await writeFile(OUT, text);
console.log(`props read       : ${props.length} (${unknown} without zdim)`);
console.log(`FURNI_DIMS       : ${dimLines.length} multi-tile entries`);
console.log(`FURNI_LOGIC      : ${logicLines.length} non-default entries`);
console.log(check ? (changed ? 'DRIFT: js/furniDims.js differs from the data' : 'js/furniDims.js is up to date') : changed ? 'rewrote js/furniDims.js' : 'js/furniDims.js already up to date');
if (check && changed) process.exitCode = 1;
